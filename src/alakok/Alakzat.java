package alakok;

public abstract class Alakzat {
     double a;
     double b;
    double r;
    public Alakzat(double a, double b) {
        this.a = a;
        this.b = b;
    }
    public Alakzat(double radio) {
        this.r = r;
    }
    
    public double getA() {
        return a;
    }
    public double getB() {
        return b;
    }
    public double getR() {
        return r;
    }
    
    
    
}
